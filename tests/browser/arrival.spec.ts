import { expect, test } from '@playwright/test'
test('fictional arrivals support batch, replay, household lookup and outside waitlists', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/?view=parking')
  const canvas = page.locator('.parking-canvas')
  await expect(canvas).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: '整批進場', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '8')
  await expect(canvas).toHaveAttribute('data-bubble-count', '0')
  await expect.poll(async () => Number(await canvas.getAttribute('data-arrival-seconds'))).toBeGreaterThan(2)
  await page.screenshot({ path: '../tmp/arrival-motorcycle-moving.png' })
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-seconds', '30.0')
  await page.screenshot({ path: '../tmp/arrival-motorcycle-result.png' })
  // Select the actual vehicle at bay 21 in the fixed default camera view.
  const renderCanvas = canvas.locator('canvas')
  const bounds = await renderCanvas.boundingBox()
  await renderCanvas.click({ position: { x: bounds!.width * 0.244, y: bounds!.height * 0.372 } })
  await expect(canvas).toHaveAttribute('data-active-arrival', '999-2')
  await expect(canvas).toHaveAttribute('data-bubble-count', '1')
  await page.getByText('示範戶號與配位', { exact: true }).click()
  await page.getByRole('button', { name: '999-1', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-bubble-count', '1')
  await expect(canvas).toHaveAttribute('data-active-arrival', '999-1')
  await page.getByRole('button', { name: '999-2', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-active-arrival', '999-2')
  await expect(canvas).toHaveAttribute('data-bubble-count', '1')
  await page.screenshot({ path: '../tmp/arrival-selected-bubble.png' })
  await page.getByRole('button', { name: '關閉對話框', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-bubble-count', '0')
  await page.getByLabel('查詢戶號（示範）').fill('999-7')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '1')
  await expect(canvas).toHaveAttribute('data-bubble-count', '1')
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await page.screenshot({ path: '../tmp/arrival-waitlist.png' })
  await page.getByRole('button', { name: '1F 腳踏車', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-enabled', 'false')
  await page.getByRole('button', { name: '整批進場', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '7')
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await page.screenshot({ path: '../tmp/arrival-bicycle-result.png' })
  await page.getByLabel('查詢戶號（示範）').fill('999-3')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '1')
  await expect(canvas).toHaveAttribute('data-active-arrival', '999-3')
  await expect(page.locator('.arrival-active-info')).not.toContainText('小39')
  await expect.poll(async () => Number(await canvas.getAttribute('data-arrival-seconds'))).toBeGreaterThan(2)
  await page.screenshot({ path: '../tmp/arrival-bicycle-query-bubble.png' })
  await page.getByRole('button', { name: '俯視', exact: true }).click()
  await page.screenshot({ path: '../tmp/arrival-bubble-top.png' })
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await expect(page.locator('.arrival-active-info')).toContainText('車位 小39')
  await page.screenshot({ path: '../tmp/arrival-bubble-arrived.png' })
  await page.getByLabel('查詢戶號（示範）').fill('000-0')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('查無示範戶號')
  expect(errors).toEqual([])
})
