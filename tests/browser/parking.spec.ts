import { expect, test } from '@playwright/test'

test('3D motorcycle and bicycle plans render with source numbering, split preview, selection and camera controls', async ({ page }) => {
  const errors: string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  const requests:string[]=[]
  page.on('request',request=>{if(request.url().includes('/api/v1'))requests.push(request.url())})
  await page.goto('/?view=parking')
  const canvas=page.locator('.parking-canvas')
  await expect(canvas).toHaveAttribute('data-ready','true')
  await expect(canvas).toHaveAttribute('data-space-count','150')
  await expect(canvas.locator('canvas')).toBeVisible()
  await page.getByLabel('車位編號',{exact:true}).fill('14')
  await page.getByRole('button',{name:'定位',exact:true}).click()
  await expect(canvas).toHaveAttribute('data-selected','14')
  await expect(page.getByText('無障礙原格',{exact:true})).toBeVisible()
  await page.getByLabel('預覽三處無障礙位拆分').check()
  await expect(canvas).toHaveAttribute('data-space-count','153')
  await page.getByLabel('車位編號',{exact:true}).fill('14-1')
  await page.getByRole('button',{name:'定位',exact:true}).click()
  await expect(canvas).toHaveAttribute('data-selected','14-1')
  await page.getByRole('button',{name:'重設'}).click()
  await page.screenshot({path:'../tmp/parking-motorcycle-3d.png'})
  await page.getByRole('button',{name:'俯視',exact:true}).click()
  await page.screenshot({path:'../tmp/parking-motorcycle-top.png'})
  await page.getByRole('button',{name:'1F 腳踏車',exact:true}).click()
  await expect(canvas).toHaveAttribute('data-ready','true')
  await expect(canvas).toHaveAttribute('data-space-count','57')
  await page.getByLabel('車位編號',{exact:true}).fill('小39')
  await page.getByRole('button',{name:'定位',exact:true}).click()
  await expect(canvas).toHaveAttribute('data-selected','小39')
  await page.getByRole('button',{name:'重設'}).click()
  await page.screenshot({path:'../tmp/parking-bicycle-top.png'})
  await page.getByRole('button',{name:'斜俯視',exact:true}).click()
  await page.screenshot({path:'../tmp/parking-bicycle-3d.png'})
  expect(requests).toEqual([])
  expect(errors).toEqual([])
})
