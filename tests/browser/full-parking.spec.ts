import { expect, test } from '@playwright/test'
test('full coverage previews every bay, supports split layouts, scrubbing and a single route replay', async ({ page }) => {
  const errors: string[] = [], api: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (r.url().includes('/api/v1')) api.push(r.url()) })
  await page.goto('/?view=parking&source=all')
  const canvas = page.locator('.parking-canvas')
  await expect(canvas).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: '整批進場', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '150')
  await expect(canvas).toHaveAttribute('data-route-issues', '0')
  await page.getByLabel('播放速度').selectOption('4')
  await expect.poll(async () => Number(await canvas.getAttribute('data-arrival-seconds'))).toBeGreaterThan(4)
  await page.getByLabel('播放進度', { exact: false }).fill('10')
  await expect(canvas).toHaveAttribute('data-arrival-seconds', '10.0')
  await page.screenshot({ path: '../tmp/full-parking-motorcycle-moving.png' })
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await page.screenshot({ path: '../tmp/full-parking-motorcycle-result.png' })
  await page.getByLabel('單一車位路線').selectOption('127')
  await page.getByRole('button', { name: '重播此車位', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '1')
  await expect(canvas).toHaveAttribute('data-bubble-count', '1')
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await expect(page.locator('.arrival-active-info')).toContainText('車位 127')
  await page.getByLabel('預覽三處無障礙位拆分').check()
  await page.getByRole('button', { name: '整批進場', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '153')
  await expect(canvas).toHaveAttribute('data-route-issues', '0')
  await page.getByRole('button', { name: '1F 腳踏車', exact: true }).click()
  await page.getByRole('button', { name: '整批進場', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-arrival-count', '57')
  await expect(canvas).toHaveAttribute('data-route-issues', '0')
  await page.getByRole('button', { name: '顯示結果', exact: true }).click()
  await page.screenshot({ path: '../tmp/full-parking-bicycle-result.png' })
  expect(errors).toEqual([])
  expect(api).toEqual([])
})
